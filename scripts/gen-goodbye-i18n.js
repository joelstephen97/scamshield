#!/usr/bin/env node
/* scripts/gen-goodbye-i18n.js — builds the inline dictionary inside goodbye.html (0.15.0, Task 19).
 *
 * goodbye.html is a static page on GitHub Pages (chrome.runtime.setUninstallURL opens it AFTER the extension is gone),
 * so it cannot use chrome.i18n or any extension API. Instead its strings are copied from the extension's own
 * _locales/<lang>/messages.json into one small object between the GB-DICT markers in the page, so the two cannot
 * drift: edit the `gb*` keys in _locales (all 20 locales), then run
 *
 *     node scripts/gen-goodbye-i18n.js            # rewrite goodbye.html
 *     node scripts/gen-goodbye-i18n.js --check    # exit 1 if goodbye.html is out of sync (CI / unit test does this)
 *
 * Placeholders ($VERSION$) become {version}. The page picks a locale from navigator.languages and falls back to English
 * per key. Nothing here is fetched at runtime: the page makes no network request.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PAGE = path.join(ROOT, 'goodbye.html');
// Keys the page uses. privacyPolicyLink / reportMistake are shared with the extension UI.
const KEYS = ['gbTitle', 'gbUninstalledV', 'gbPick', 'gbR1', 'gbR2', 'gbR3', 'gbR4', 'gbR5', 'gbCopied', 'gbIssue', 'gbStatic', 'gbMadeBy', 'privacyPolicyLink', 'reportMistake'];
const START = '/* GB-DICT:START (generated by scripts/gen-goodbye-i18n.js - do not edit by hand) */';
const END = '/* GB-DICT:END */';

// _locales folder -> BCP 47 tag the page matches against navigator.language.
const tagOf = (dir) => dir.replace('_', '-');

function convert(entry) {
  let msg = entry.message;
  for (const [name, ph] of Object.entries(entry.placeholders || {})) {
    msg = msg.split('$' + name.toUpperCase() + '$').join('{' + name + '}');
    void ph;
  }
  return msg;
}

function dictionary() {
  const dirs = fs.readdirSync(path.join(ROOT, '_locales'), { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  const out = {};
  for (const dir of dirs) {
    const f = path.join(ROOT, '_locales', dir, 'messages.json');
    if (!fs.existsSync(f)) continue;
    const data = JSON.parse(fs.readFileSync(f, 'utf8'));
    const o = {};
    for (const k of KEYS) {
      if (!data[k]) throw new Error(dir + ': missing key ' + k);
      o[k] = convert(data[k]);
    }
    out[tagOf(dir)] = o;
  }
  if (!out.en) throw new Error('en locale missing');
  return out;
}

function block() {
  const d = dictionary();
  const lines = Object.keys(d).map((tag) => JSON.stringify(tag) + ':' + JSON.stringify(d[tag]));
  // JSON.stringify never emits "</script" for these strings, but keep the page safe if a future string ever did.
  return START + '\nvar GB_DICT={\n' + lines.join(',\n').replace(/<\/(script)/gi, '<\\/$1') + '\n};\n' + END;
}

function inject(html) {
  const a = html.indexOf(START), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('GB-DICT markers not found in goodbye.html');
  return html.slice(0, a) + block() + html.slice(b + END.length);
}

if (require.main === module) {
  const html = fs.readFileSync(PAGE, 'utf8');
  const crlf = html.includes('\r\n');
  const next = inject(html.replace(/\r\n/g, '\n'));
  const cur = html.replace(/\r\n/g, '\n');
  if (process.argv.includes('--check')) {
    if (next !== cur) { console.error('goodbye.html is out of sync with _locales: run node scripts/gen-goodbye-i18n.js'); process.exit(1); }
    console.log('goodbye.html dictionary is in sync');
  } else {
    fs.writeFileSync(PAGE, crlf ? next.replace(/\n/g, '\r\n') : next);
    console.log('goodbye.html dictionary written (' + Object.keys(dictionary()).length + ' locales)');
  }
}

module.exports = { KEYS, START, END, dictionary, block, inject };
